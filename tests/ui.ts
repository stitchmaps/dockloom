import { _electron as electron } from 'playwright';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
const data = await mkdtemp(path.join(os.tmpdir(), 'dockloom-ui-'));
await mkdir('test-results', { recursive: true });
const env: Record<string, string> = { ...Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => entry[1] !== undefined)), DOCKLOOM_DATA_DIR: data };
delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({ ...(process.env.DOCKLOOM_EXECUTABLE ? { executablePath: process.env.DOCKLOOM_EXECUTABLE } : { args: ['.'] }), env, timeout: 30000 });
try {
  const page = await app.firstWindow();
  page.setDefaultTimeout(15000);
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.getByRole('heading', { name: '从一台服务器开始' }).waitFor();
  assert.equal(await page.evaluate(() => typeof window.dockloom?.inspect), 'function');
  assert.equal(await page.evaluate(() => typeof window.dockloom?.planCompose), 'function');
  assert.equal(await page.evaluate(() => typeof window.dockloom?.deployCompose), 'function');
  console.log('PASS actual Electron window + preload bridge + empty onboarding');
  await page.getByRole('button', { name: '添加服务器', exact: true }).last().click();
  await page.getByRole('textbox', { name: '显示名称', exact: true }).fill('Local test connection');
  await page.getByRole('textbox', { name: '主机地址', exact: true }).fill('127.0.0.1');
  await page.getByRole('spinbutton', { name: 'SSH 端口', exact: true }).fill('1');
  await page.getByRole('button', { name: '保存连接', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  const saved = await page.evaluate(() => window.dockloom!.listServers());
  assert.equal(saved.length, 1); assert.equal(saved[0].root, '~/deployments');
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.getByRole('button', { name: '移除连接', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: '移除连接', exact: true }).click();
  assert.equal((await page.evaluate(() => window.dockloom!.listServers())).length, 0);
  await page.getByRole('button', { name: '应用', exact: true }).click();
  console.log('PASS real IPC connection persistence + ~/root validation + local removal');
  await page.getByRole('switch', { name: '演示模式' }).click();
  await page.getByRole('button', { name: /portfolio-web-1/ }).waitFor();
  await page.screenshot({ path: 'test-results/workspace.png', fullPage: true });
  await page.getByRole('textbox', { name: '搜索项目、容器或镜像…' }).fill('notes');
  assert.equal(await page.getByRole('button', { name: /portfolio-web-1/ }).count(), 0);
  await page.getByRole('button', { name: /notes-api-1/ }).click();
  await page.getByRole('button', { name: '停止', exact: true }).click();
  await page.getByRole('button', { name: '确认执行', exact: true }).click();
  await page.locator('.detail-panel .status').filter({ hasText: '已退出' }).waitFor();
  console.log('PASS search + container detail + explicit stop confirmation (demo)');
  await page.getByRole('button', { name: '部署静态站点', exact: true }).click();
  await page.getByRole('textbox', { name: /应用名称/ }).fill('ui-site');
  await page.getByRole('button', { name: '选择目录', exact: true }).click();
  await page.getByRole('button', { name: '生成部署计划', exact: true }).click();
  await page.screenshot({ path: 'test-results/deploy-review.png', fullPage: true });
  const dialog = page.getByRole('dialog');
  await dialog.locator('button.primary').click();
  await page.locator('.job-detail .status').filter({ hasText: '已完成' }).waitFor();
  console.log('PASS deployment review + job completion + version history (demo)');
  await page.getByRole('button', { name: '部署 Compose', exact: true }).click();
  await page.getByRole('textbox', { name: /应用名称/ }).fill('ui-stack');
  await page.getByRole('button', { name: '选择目录', exact: true }).click();
  await page.getByRole('textbox', { name: /配置文件（每行一个）/ }).fill('compose.yaml\nproduction.yaml');
  await page.getByRole('textbox', { name: /环境文件（每行一个）/ }).fill('.env.production');
  await page.getByRole('textbox', { name: /Profiles（每行一个）/ }).fill('production');
  await page.getByRole('button', { name: '生成部署计划', exact: true }).click();
  await dialog.getByRole('heading', { name: '将发布的服务', exact: true }).waitFor();
  assert.equal(await dialog.locator('.plan-summary code').allTextContents().then(names => names.join(',')), 'web,db');
  await page.screenshot({ path: 'test-results/compose-review.png', fullPage: true });
  await dialog.locator('button.primary').click();
  await page.locator('.job-detail .status').filter({ hasText: '已完成' }).waitFor();
  console.log('PASS Compose review services + ordered files/env/profiles + deployment job (demo)');
  await page.getByRole('button', { name: '界面语言', exact: true }).click();
  await page.getByRole('heading', { name: 'Deployments', exact: true }).waitFor();
  await page.getByRole('button', { name: /Staging staging.example.com/ }).click();
  await page.getByRole('button', { name: 'Applications', exact: true }).click();
  await page.getByRole('button', { name: /preview-web-1/ }).waitFor();
  assert.equal(await page.getByRole('button', { name: /notes-api-1/ }).count(), 0);
  console.log('PASS language switch + server isolation');
  assert.deepEqual(errors, []);
  console.log('ALL UI CHECKS PASSED');
} finally {
  await app.close();
  await rm(data, { recursive: true, force: true });
}
